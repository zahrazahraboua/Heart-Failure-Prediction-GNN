    edge_index = torch.tensor(np.array(knn_graph.nonzero()), dtype=torch.long)

    edge_index_with_loops = torch_geometric.utils.add_self_loops(edge_index)[0]


    return Data(x=x, edge_index=edge_index_with_loops, y=y)


